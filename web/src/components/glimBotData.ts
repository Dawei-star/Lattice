/** 解码一条 base64 点环串为扁平坐标 [x0, y0, x1, y1, …]（×100 定点还原）。 */
function decodeFlat(base64: string): Float64Array {
  const bin = atob(base64);
  const out = new Float64Array(bin.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) / 100;
  }
  return out;
}

